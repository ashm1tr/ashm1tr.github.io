// each generated page names the sources it came from; the wipe guard below
// looks only for the common prefix, so both trees are covered by one check
const MARKER = (src) => `<!-- generated by build.js — edit the markdown in ${src}/, not this file -->`;
const GENERATED = "<!-- generated by build.js";

const withDrafts = process.argv.includes("--drafts");

/* ---------- helpers ---------- */

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const MONTHS = ["jan","feb","mar","apr","may","jun","jul","aug","sep","oct","nov","dec"];
// dates are formatted from the iso string, never from a clock, so that a
// rebuild on a different day produces byte-identical output
function human(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  return `${d} ${MONTHS[m - 1]} ${y}`;
}
function rfc822(iso) {
  return new Date(`${iso}T12:00:00Z`).toUTCString();
}

// a deliberately small front-matter subset: "key: value" lines, no nesting
function frontMatter(raw, file) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!m) throw new Error(`${file}: missing --- front matter block`);
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    if (!line.trim()) continue;
    const at = line.indexOf(":");
    if (at === -1) throw new Error(`${file}: bad front-matter line "${line}"`);
    meta[line.slice(0, at).trim()] = line.slice(at + 1).trim();
  }
  return { meta, body: raw.slice(m[0].length) };
}

/* ---------- markdown ---------- */

const THEOREMS = ["theorem", "lemma", "definition", "proof", "remark"];

const highlighter = await createHighlighter({
  themes: ["vitesse-light", "vitesse-dark"],
  langs: ["lean4", "python", "haskell", "rust", "bash", "javascript", "typescript",
          "json", "html", "css", "sql", "c", "cpp", "latex", "diff", "text"],
});

const md = new MarkdownIt({
  html: true,      // an escape hatch for the odd bit of raw markup
  linkify: true,
  typographer: false, // straight quotes suit a monospace page
  highlight(code, lang) {
    const known = highlighter.getLoadedLanguages().includes(lang);
    // defaultColor:false emits both palettes as css variables, so the theme
    // toggle drives code colour from style.css with no javascript
    return highlighter.codeToHtml(code.replace(/\n$/, ""), {
      lang: known ? lang : "text",
      themes: { light: "vitesse-light", dark: "vitesse-dark" },
      defaultColor: false,
    });
  },
});

md.use(footnote);
md.use(katexPlugin.default ?? katexPlugin);
md.use(anchor, {
  level: [2, 3, 4],
  permalink: anchor.permalink.linkInsideHeader({
    symbol: "#", placement: "after", class: "anchor", ariaHidden: true,
  }),
});
for (const kind of THEOREMS) {
  md.use(container, kind, {
    render(tokens, i) {
      if (tokens[i].nesting !== 1) return "</div>\n";
      const name = tokens[i].info.trim().slice(kind.length).trim();
      const label = name ? `${kind} — ${name}` : kind;
      return `<div class="thm thm--${kind}"><p class="thm-label">${esc(label)}</p>\n`;
    },
  });
}

// the post title already occupies <h2>, so "## foo" in a post becomes <h3>
md.core.ruler.push("demote_headings", (state) => {
  for (const t of state.tokens) {
    if (t.type === "heading_open" || t.type === "heading_close") {
      t.tag = "h" + Math.min(Number(t.tag.slice(1)) + 1, 6);
    }
  }
});

// footnote headings would duplicate the post's own <h2>; drop the rule/label
md.renderer.rules.footnote_block_open = () =>
  '<hr class="footnote-rule">\n<ol class="footnotes">\n';
md.renderer.rules.footnote_block_close = () => "</ol>\n";

/* ---------- page chrome ---------- */

function nav(current) {
  const items = [["/", "home"], ["/reading/", "reading"], [`/${SITE.seg}/`, SITE.seg], ["/uni/", "uni"]];
  return items.map(([href, label]) =>
    `<a href="${href}"${label === current ? ' aria-current="page"' : ""}>${label}</a>`
  ).join("\n      ");
}

// the only visible way to subscribe: the autodiscovery <link> in <head> is
// invisible to a reader. It rides the writing pages alone, since they are the
// only ones the feed covers.
const feedLink = `<a href="/${SITE.seg}/feed.xml">rss</a>`;

