// build.js — renders posts/*.md into /writing/ and modules/ into /uni/.
//
// maths and syntax highlighting are resolved here rather than in the browser,
// so a published post carries no javascript and never flashes raw "$x^2$".
// a post that uses neither also links neither stylesheet.
//
//   node build.js            build posts/ into writing/
//   node build.js --drafts   also build drafts/, for local preview only
//
// the output is a pure function of the sources: writing/ and uni/ are wiped
// and regenerated each run, which is what lets ci detect a stale commit.

