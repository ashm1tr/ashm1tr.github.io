/* ---------- load posts ---------- */

function load(dir, isDraft) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => f.endsWith(".md")).map((file) => {
    const full = path.join(dir, file);
    const { meta, body } = frontMatter(fs.readFileSync(full, "utf8"), file);
    for (const key of ["title", "date", "description"]) {
      if (!meta[key]) throw new Error(`${file}: front matter needs a "${key}"`);
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(meta.date)) {
      throw new Error(`${file}: date must be YYYY-MM-DD, got "${meta.date}"`);
    }
    const html = md.render(body);
    const words = html.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length;
    return {
      slug: file.replace(/\.md$/, ""),
      title: meta.title,
      date: meta.date,
      updated: meta.updated || null,
      description: meta.description,
      html,
      isDraft,
      words,
      minutes: Math.max(1, Math.round(words / 200)),
      // the build knows what it actually rendered, so assets stay opt-in
      usesMath: html.includes('class="katex'),
    };
  });
}

const posts = [...load(path.join(ROOT, "posts"), false),
               ...(withDrafts ? load(path.join(ROOT, "drafts"), true) : [])]
  .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug < b.slug ? 1 : -1));

const seen = new Set();
for (const p of posts) {
  if (seen.has(p.slug)) throw new Error(`duplicate slug "${p.slug}"`);
  seen.add(p.slug);
}

